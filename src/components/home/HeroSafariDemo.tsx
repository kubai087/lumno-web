function createScopeMenu(
  copy: ScopeMenuCopy,
  providers: LumnoBuiltinSiteSearchProvider[],
): SiteSearchScopeMenuModel {
  const providerItems = providers.map((provider) => ({
    active: provider.key === "gh",
    favicon: `${LUMNO_SITE_SEARCH_ICON_ROOT}/tile-${provider.key}.png`,
    iconClass:
      provider.category === "aiSearch" ||
      provider.action === "openAndSubmit" ||
      !provider.template.includes("{query}")
        ? "ri-search-ai-line"
        : "ri-global-line",
    id: `provider:${provider.key}`,
    label: provider.name,
    provider,
  }));
  const isAiProvider = (item: (typeof providerItems)[number]) =>
    item.provider.category === "aiSearch" ||
    item.provider.action === "openAndSubmit" ||
    !item.provider.template.includes("{query}");
  const isSearchEngine = (item: (typeof providerItems)[number]) =>
    item.provider.category === "searchEngine";

  return {
    ariaLabel: copy.ariaLabel,
    filterLabel: copy.filterLabel,
    groups: [
      {
        label: copy.searchGroup,
        items: providerItems.filter(isSearchEngine),
      },
      {
        label: copy.siteGroup,
        items: providerItems.filter(
          (item) => !isSearchEngine(item) && !isAiProvider(item),
        ),
      },
      {
        label: copy.aiGroup,
        items: providerItems.filter(isAiProvider),
      },
      {
        label: copy.browserGroup,
        items: [
          { iconClass: "ri-window-line", id: "openTabs", label: copy.openTabs },
          { iconClass: "ri-star-line", id: "local:topSite", label: copy.topSites },
          { iconClass: "ri-bookmark-3-line", id: "local:bookmark", label: copy.bookmark },
          { iconClass: "ri-history-line", id: "local:history", label: copy.history },
        ],
      },
    ],
    navigationLabel: copy.navigationLabel,
    selectLabel: copy.selectLabel,
  };
}

