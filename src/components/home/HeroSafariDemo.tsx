interface HomeIntroRect {
  bottom: number;
  height: number;
  left: number;
  right: number;
  top: number;
  width: number;
}

const toHomeIntroRect = (rect: DOMRect): HomeIntroRect => ({
  bottom: rect.bottom,
  height: rect.height,
  left: rect.left,
  right: rect.right,
  top: rect.top,
  width: rect.width,
});

const getHomeIntroRectDelta = (
  first: HomeIntroRect,
  second: HomeIntroRect,
) => Math.max(
  Math.abs(first.left - second.left),
  Math.abs(first.top - second.top),
  Math.abs(first.width - second.width),
  Math.abs(first.height - second.height),
);

const toDocumentHomeIntroRect = (
  rect: HomeIntroRect,
  scrollX: number,
  scrollY: number,
): HomeIntroRect => ({
  ...rect,
  bottom: rect.bottom + scrollY,
  left: rect.left + scrollX,
  right: rect.right + scrollX,
  top: rect.top + scrollY,
});

