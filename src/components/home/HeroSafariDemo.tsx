export function HeroSafariDemo({
  ariaLabel,
  builtinSiteSearchProviders,
  locale,
}: HeroSafariDemoProps) {
  const reducedMotion = usePrefersReducedMotion();
  const copy = COPY_BY_LOCALE[locale];
  const initialSceneIndex = Math.max(
    0,
    copy.scenes.findIndex((item) => item.id === "site-search"),
  );
  const [sceneIndex, setSceneIndex] = useState(initialSceneIndex);
  const [sceneDirection, setSceneDirection] = useState<SceneDirection>("forward");
  const [replayKey, setReplayKey] = useState(0);
  const [isAutoPlaying, setIsAutoPlaying] = useState(true);
  const autoPlayTimerRef = useRef<number | null>(null);
  const sceneIndexRef = useRef(initialSceneIndex);
  const scene = copy.scenes[sceneIndex] || copy.scenes[0];

  const showScene = useCallback(
    (
      nextSceneIndex: number,
      direction?: SceneDirection,
    ) => {
      const resolvedDirection =
        direction ||
        (nextSceneIndex < sceneIndexRef.current ? "backward" : "forward");

      sceneIndexRef.current = nextSceneIndex;
      setSceneDirection(resolvedDirection);
      setSceneIndex(nextSceneIndex);
      setReplayKey((currentKey) => currentKey + 1);
    },
    [],
  );

  useEffect(() => {
    let cancelled = false;

    if (autoPlayTimerRef.current !== null) {
      window.clearTimeout(autoPlayTimerRef.current);
      autoPlayTimerRef.current = null;
    }

    const finalSceneIndex = Math.max(
      0,
      copy.scenes.findIndex((item) => item.id === "browser-search"),
    );

    if (reducedMotion) {
      setIsAutoPlaying(false);
      showScene(finalSceneIndex, "forward");
      return () => {
        cancelled = true;
      };
    }

    setIsAutoPlaying(true);

    const playStep = (sequenceIndex: number) => {
      if (cancelled) {
        return;
      }

      const step = HERO_INTRO_SEQUENCE[sequenceIndex];
      if (!step) {
        setIsAutoPlaying(false);
        autoPlayTimerRef.current = null;
        return;
      }

      const nextSceneIndex = copy.scenes.findIndex(
        (item) => item.id === step.id,
      );
      if (nextSceneIndex < 0) {
        playStep(sequenceIndex + 1);
        return;
      }

      showScene(nextSceneIndex, "forward");
      autoPlayTimerRef.current = window.setTimeout(() => {
        playStep(sequenceIndex + 1);
      }, step.durationMs);
    };

    playStep(0);

    return () => {
      cancelled = true;
      if (autoPlayTimerRef.current !== null) {
        window.clearTimeout(autoPlayTimerRef.current);
        autoPlayTimerRef.current = null;
      }
    };
  }, [copy.scenes, locale, reducedMotion, showScene]);

  const handleSceneSelect = (nextSceneIndex: number) => {
    if (autoPlayTimerRef.current !== null) {
      window.clearTimeout(autoPlayTimerRef.current);
      autoPlayTimerRef.current = null;
    }
    setIsAutoPlaying(false);
    showScene(nextSceneIndex);
  };

  const isBrowserSearch = scene.id === "browser-search";
  const isSiteSearch = scene.id === "site-search";
  const animationKey = `${locale}-${scene.id}-${replayKey}`;
  const siteSearchDemoModel = useMemo(
    () => ({
      ...copy.siteSearchDemo,
      scopeMenu: createScopeMenu(
        copy.scopeMenuCopy,
        builtinSiteSearchProviders,
      ),
    }),
    [builtinSiteSearchProviders, copy],
  );

  const model: BookmarkFocusModel = {
    hoverLeadMs: isBrowserSearch ? 1040 : 0,
    hoverStartMs: 3200,
    hoverStepMs: isBrowserSearch ? 1600 : 0,
    hoverWrapStepMs: isBrowserSearch ? 1600 : 0,
    openLabel: copy.openLabel,
    overlayAriaLabel: "Lumno overlay demo",
    panelId: PANEL_ID,
    query: scene.query,
    reducedMotion,
    removeHistoryLabel: copy.removeHistoryLabel,
    results: scene.results,
    searchAriaLabel: "Search Lumno demo",
    sceneId: animationKey,
    settingsLabel: copy.settingsLabel,
  };

  return (
    <div className="hero-safari-demo" data-active-demo-scene={scene.id}>
      <DitherShader
        src="/assets/settings-bg-light-monet-newtab.webp"
        gridSize={2}
        ditherMode="bayer"
        colorMode="original"
        brightness={0.01}
        contrast={1.08}
        threshold={0.22}
      />
      <div aria-hidden="true" className="hero-safari-screen" inert>
        <AnimatePresence custom={sceneDirection} mode="wait">
          <motion.div
            animate="center"
            className="hero-safari-stage"
            custom={sceneDirection}
            data-scene-direction={sceneDirection}
            data-scene-id={scene.id}
            exit={reducedMotion ? undefined : "exit"}
            initial={reducedMotion ? false : "enter"}
            key={animationKey}
            variants={reducedMotion ? undefined : HERO_SCENE_VARIANTS}
          >
            <div className={isSiteSearch ? "site-search-demo-ui" : "bookmark-focus-ui"}>
              {isSiteSearch ? (
                <div className="site-search-demo-surface" key={animationKey}>
                  <SiteSearchDemoSurface model={siteSearchDemoModel} />
                </div>
              ) : (
                <BookmarkFocusDemo key={animationKey} model={model} />
              )}
            </div>
            <div
              className="cursor-layer"
              data-cursor-mode={
                isBrowserSearch ? "setup" : isSiteSearch ? "site-search" : "commands"
              }
              key={`cursor-${animationKey}`}
            >
              <DemoCursor />
            </div>
          </motion.div>
        </AnimatePresence>
      </div>
      <div
        aria-label={copy.scenePickerLabel}
        className="hero-demo-page-switcher"
        data-auto-playing={isAutoPlaying ? "true" : "false"}
        role="group"
        style={
          {
            "--hero-demo-scene-count": copy.scenes.length,
            "--hero-demo-scene-index": sceneIndex,
          } as CSSProperties
        }
      >
        <span aria-hidden="true" className="hero-demo-page-indicator" />
        {copy.scenes.map((item, index) => (
          <button
            aria-label={`${item.label} · ${ariaLabel}`}
            aria-pressed={index === sceneIndex}
            className="hero-demo-page-button"
            data-active={index === sceneIndex ? "true" : "false"}
            key={item.id}
            onClick={() => handleSceneSelect(index)}
            type="button"
          >
            {item.label}
          </button>
        ))}
      </div>
    </div>
  );
}
