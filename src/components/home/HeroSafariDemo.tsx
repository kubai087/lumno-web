function DemoCursorLayer({ mode, timing }: { mode: CursorMode; timing: SearchResultCursorTiming }) {
  const layerRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const layer = layerRef.current;
    const stage = layer?.parentElement;
    if (!stage) {
      return undefined;
    }

    let animationFrame = 0;
    const setCursorPoint = (
      name: string,
      target: Element | null,
      horizontalRatio: number,
      verticalRatio: number,
    ) => {
      if (!target) {
        return;
      }

      const stageRect = stage.getBoundingClientRect();
      const targetRect = target.getBoundingClientRect();
      const stageScaleX = stageRect.width / Math.max(stage.offsetWidth, 1);
      const stageScaleY = stageRect.height / Math.max(stage.offsetHeight, 1);
      const renderedLeft = targetRect.left - stageRect.left
        + targetRect.width * horizontalRatio;
      const renderedTop = targetRect.top - stageRect.top
        + targetRect.height * verticalRatio;
      const left = renderedLeft / Math.max(stageScaleX, Number.EPSILON)
        - CURSOR_TIP_OFFSET_X;
      const top = renderedTop / Math.max(stageScaleY, Number.EPSILON)
        - CURSOR_TIP_OFFSET_Y;

      stage.style.setProperty(`--${name}-cursor-left`, `${left.toFixed(2)}px`);
      stage.style.setProperty(`--${name}-cursor-top`, `${top.toFixed(2)}px`);
    };
    const syncCursorTargets = () => {
      if (mode === "search-result") {
        // Rests on the field's leading edge while the query types, then
        // moves to the first result. Measured, so it tracks the panel's
        // placement at any card size.
        setCursorPoint(
          "search-result-input",
          stage.querySelector(".lumno-overlay-query"),
          0.01,
          0.72,
        );
        setCursorPoint(
          "search-result",
          stage.querySelector('.lumno-overlay-result[data-demo-index="0"]'),
          0.7,
          0.5,
        );
        return;
      }

      setCursorPoint(
        "site-search-tag",
        stage.querySelector('[data-demo-cursor-target="site-search-tag"]'),
        0.5,
        0.5,
      );
      setCursorPoint(
        "site-search-menu",
        stage.querySelector('[data-demo-cursor-target="site-search-menu"]'),
        0.3,
        0.3,
      );
    };
    const scheduleCursorSync = () => {
      window.cancelAnimationFrame(animationFrame);
      animationFrame = window.requestAnimationFrame(syncCursorTargets);
    };

    scheduleCursorSync();
    const syncDelays = mode === "search-result"
      ? timing.syncMs
      : [2_800, 4_800, 6_350];
    const timeoutIds = syncDelays.map((delay) => window.setTimeout(
      scheduleCursorSync,
      delay,
    ));
    document.addEventListener("lumno:home-intro-complete", scheduleCursorSync);
    window.addEventListener("resize", scheduleCursorSync, { passive: true });

    return () => {
      window.cancelAnimationFrame(animationFrame);
      timeoutIds.forEach((timeoutId) => window.clearTimeout(timeoutId));
      document.removeEventListener("lumno:home-intro-complete", scheduleCursorSync);
      window.removeEventListener("resize", scheduleCursorSync);
    };
  }, [mode, timing]);

  return (
    <div
      className="cursor-layer"
      data-cursor-mode={mode}
      ref={layerRef}
      style={{
        "--search-result-cursor-delay": `${timing.delayMs}ms`,
        "--search-result-cursor-duration": `${timing.durationMs}ms`,
      } as CSSProperties}
    >
      <DemoCursor />
    </div>
  );
}

function CommandSceneDemo({
  followups,
  model,
}: {
  followups: NonNullable<DemoScene["followups"]>;
  model: BookmarkFocusModel;
}) {
  const [phaseIndex, setPhaseIndex] = useState(model.reducedMotion ? 1 : 0);

  useEffect(() => {
    if (model.reducedMotion) {
      setPhaseIndex(1);
      return undefined;
    }

    setPhaseIndex(0);
    const timeoutIds = followups.map((_, index) => window.setTimeout(() => {
      setPhaseIndex(index + 1);
    }, COMMAND_BROWSER_PAGE_START_MS + index * COMMAND_BROWSER_PAGE_HOLD_MS));

    return () => timeoutIds.forEach((timeoutId) => window.clearTimeout(timeoutId));
  }, [followups.length, model.reducedMotion, model.sceneId]);

  const followup = phaseIndex > 0 ? followups[phaseIndex - 1] : undefined;
  const activeModel: BookmarkFocusModel = followup
    ? {
        ...model,
        presentation: "complete",
        query: followup.query,
        results: followup.results,
        sceneId: `${model.sceneId}-${followup.id}`,
      }
    : model;
  const phaseId = followup?.id || "slash-commands";

  return (
    <AnimatePresence initial={false} mode="wait">
      <motion.div
        animate="center"
        className="bookmark-focus-demo-phase"
        data-command-demo-phase={phaseId}
        exit={model.reducedMotion ? undefined : "exit"}
        initial={model.reducedMotion ? false : "enter"}
        key={phaseId}
        variants={model.reducedMotion ? undefined : COMMAND_PHASE_VARIANTS}
      >
        <BookmarkFocusDemo model={activeModel} />
      </motion.div>
    </AnimatePresence>
  );
}

